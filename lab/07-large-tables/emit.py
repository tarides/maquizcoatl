#!/usr/bin/env python3
"""Experiment #7: parse upstream/src/unicode_property_data.c and emit the
table in each prover's syntax.

Usage: emit.py <unicode_property_data.c> <outdir> [--limit N]

--limit N keeps only the first N CodeRanges entries (bisection).
Writes <outdir>/table.json, per-tool sources, and <outdir>/emitted.tsv
(file, bytes, sha256).  Python 3.12, stdlib only.
"""
import hashlib, json, os, re, sys

def parse(path):
    s = open(path, encoding="ascii").read()
    arrays = {}
    order = []
    for m in re.finditer(r"static const OnigCodePoint\s+CR_(\w+)\[\]\s*=\s*\{\s*(\d+),(.*?)\};", s, re.S):
        name, n, body = m.group(1), int(m.group(2)), m.group(3)
        nums = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", re.sub(r"/\*.*?\*/", "", body, flags=re.S))]
        assert len(nums) == 2 * n, (name, n, len(nums))
        arrays[name] = [(nums[i], nums[i + 1]) for i in range(0, len(nums), 2)]
        order.append(name)
    aliases = dict(re.findall(r"^#define CR_(\w+) CR_(\w+)$", s, re.M))
    m = re.search(r"const CodeRanges\[\] = \{(.*?)\};", s, re.S)
    cr = re.findall(r"CR_(\w+)", m.group(1))
    def resolve(x):
        while x in aliases:
            x = aliases[x]
        return x
    code_ranges = [resolve(x) for x in cr]
    # name pool: struct fields strN[sizeof("name")]
    pool = dict((int(n), name) for n, name in re.findall(
        r"char unicode_prop_name_pool_str(\d+)\[sizeof\(\"([^\"]*)\"\)\];", s))
    names = [(pool[int(n)], int(c)) for n, c in re.findall(r"\{pool_offset\((\d+)\),\s*(\d+)\}", s)]
    names.sort()
    cnt = int(re.search(r"#define CODE_RANGES_NUM\s+(\d+)", s).group(1))
    kw = int(re.search(r"#define TOTAL_KEYWORDS (\d+)", s).group(1))
    return dict(arrays=arrays, order=order, aliases=aliases, code_ranges=code_ranges,
                names=names, CODE_RANGES_NUM=cnt, TOTAL_KEYWORDS=kw)

# ---------------------------------------------------------------- helpers
def tree(rs, leaf_false, leaf_true, lt, le, ite):
    """Balanced decision tree over sorted disjoint ranges."""
    if not rs:
        return leaf_false
    m = len(rs) // 2
    lo, hi = rs[m]
    return ite(lt(lo), tree(rs[:m], leaf_false, leaf_true, lt, le, ite),
               ite(le(hi), leaf_true, tree(rs[m + 1:], leaf_false, leaf_true, lt, le, ite)))

def used(t):
    """Arrays referenced by the kept CodeRanges entries, in definition order."""
    keep = set(t["code_ranges"])
    return [a for a in t["order"] if a in keep]

# ---------------------------------------------------------------- Rocq
def rocq(t):
    o = ["(* Generated by emit.py from upstream/src/unicode_property_data.c\n   (Oniguruma f95747b, Copyright (c) 2016-2024 K.Kosako, BSD-2-Clause). *)",
         "From Stdlib Require Import ZArith List String.",
         "Import ListNotations.", "Open Scope Z_scope.", ""]
    for a in used(t):
        o.append("Definition cr_%s : list (Z * Z) := [%s]." % (
            a, "; ".join("(%d, %d)" % r for r in t["arrays"][a])))
    o.append("Definition code_ranges : list (list (Z * Z)) := [%s]." %
             "; ".join("cr_" + a for a in t["code_ranges"]))
    o.append("Definition names : list (string * Z) := [%s]." %
             "; ".join('("%s"%%string, %d)' % nc for nc in t["names"]))
    return "\n".join(o) + "\n"

# ---------------------------------------------------------------- Lean
def lean(t):
    o = ["-- Generated by emit.py from upstream/src/unicode_property_data.c",
         "-- (Oniguruma f95747b, Copyright (c) 2016-2024 K.Kosako, BSD-2-Clause).",
         "namespace Table", ""]
    for a in used(t):
        o.append("def cr_%s : Array (UInt32 × UInt32) := #[%s]" % (
            a, ", ".join("(%d, %d)" % r for r in t["arrays"][a])))
    o.append("def codeRanges : Array (Array (UInt32 × UInt32)) := #[%s]" %
             ", ".join("cr_" + a for a in t["code_ranges"]))
    o.append("def names : Array (String × Nat) := #[%s]" %
             ", ".join('("%s", %d)' % nc for nc in t["names"]))
    o.append("\nend Table")
    return "\n".join(o) + "\n"

# ---------------------------------------------------------------- Why3
def why3(t):
    def lst(rs):
        return "".join("Cons (%d, %d) (" % r for r in rs) + "Nil" + ")" * len(rs)
    o = ["(* Generated by emit.py from upstream/src/unicode_property_data.c",
         "   (Oniguruma f95747b, Copyright (c) 2016-2024 K.Kosako, BSD-2-Clause). *)",
         "module Table", "  use int.Int", "  use list.List", "  use string.String", ""]
    for a in used(t):
        o.append("  let constant cr_%s : list (int, int) = %s" % (a, lst(t["arrays"][a])))
    # code_ranges as a dispatch function: a list-of-lists constant built from
    # the cr_* constants makes `why3 execute` fail with "Type mismatch" (Why3 1.9.0).
    o.append("  let constant num_code_ranges : int = %d" % len(t["code_ranges"]))
    o.append("  let function code_range (ct: int) : list (int, int) =\n    " +
             "\n    ".join("if ct = %d then cr_%s else" % (i, a) for i, a in enumerate(t["code_ranges"])) +
             "\n    Nil")
    o.append("  let constant names : list (string, int) = %s" %
             ("".join('Cons ("%s", %d) (' % nc for nc in t["names"]) + "Nil" + ")" * len(t["names"])))
    o.append("end")
    return "\n".join(o) + "\n"

def why3c(t):
    """Decision trees over uint32 for why3 extract -D c."""
    o = ["(* Generated by emit.py (decision-tree representation for the C target).",
         "   Data from Oniguruma f95747b, Copyright (c) 2016-2024 K.Kosako, BSD-2-Clause. *)",
         "module TableC", "  use int.Int", "  use mach.int.UInt32", "  use mach.int.Int32", ""]
    for a in used(t):
        e = tree(t["arrays"][a], "false", "true",
                 lambda lo: "c < (%d:uint32)" % lo, lambda hi: "c <= (%d:uint32)" % hi,
                 lambda c, x, y: "(if %s then %s else %s)" % (c, x, y))
        o.append("  let mem_%s (c: uint32) : bool = %s" % (a, e))
    chain = []
    for i, a in enumerate(t["code_ranges"]):
        chain.append("if ct = (%d:int32) then mem_%s c else" % (i, a))
    o.append("  let ctype_mem (ct: int32) (c: uint32) : bool =\n    " + "\n    ".join(chain) + "\n    false")
    o.append("end")
    return "\n".join(o) + "\n"

# ---------------------------------------------------------------- F*
def fstar(t):
    o = ["(* Generated by emit.py from upstream/src/unicode_property_data.c",
         "   (Oniguruma f95747b, Copyright (c) 2016-2024 K.Kosako, BSD-2-Clause). *)",
         "module Table", ""]
    for a in used(t):
        o.append("let cr_%s : list (int & int) = [%s]" % (
            a, "; ".join("(%d, %d)" % r for r in t["arrays"][a])))
    o.append("let code_ranges : list (list (int & int)) = [%s]" %
             "; ".join("cr_" + a for a in t["code_ranges"]))
    o.append("let names : list (string & int) = [%s]" %
             "; ".join('("%s", %d)' % nc for nc in t["names"]))
    return "\n".join(o) + "\n"

def fstarc(t):
    o = ["(* Generated by emit.py (decision-tree representation for the C targets).",
         "   Data from Oniguruma f95747b, Copyright (c) 2016-2024 K.Kosako, BSD-2-Clause. *)",
         "module TableC", "module U32 = FStar.UInt32", ""]
    for a in used(t):
        e = tree(t["arrays"][a], "false", "true",
                 lambda lo: "U32.lt c %dul" % lo, lambda hi: "U32.lte c %dul" % hi,
                 lambda c, x, y: "(if %s then %s else %s)" % (c, x, y))
        o.append("let mem_%s (c: U32.t) : bool = %s" % (a, e))
    chain = ["if ct = %dul then mem_%s c else" % (i, a) for i, a in enumerate(t["code_ranges"])]
    o.append("let ctype_mem (ct: U32.t) (c: U32.t) : bool =\n  " + "\n  ".join(chain) + "\n  false")
    return "\n".join(o) + "\n"

def pulse(t):
    """Pulse static arrays (Pulse.Lib.GlobalArray), lo/hi interleaved, one per
    property; linear scan; dispatch on the ctype by a balanced if-tree."""
    o = ["(* Generated by emit.py (Pulse static-array representation for the C targets).",
         "   Data from Oniguruma f95747b, Copyright (c) 2016-2024 K.Kosako, BSD-2-Clause. *)",
         "module PulseTable", "#lang-pulse", "open Pulse.Lib.Pervasives",
         "module US = FStar.SizeT", "module U32 = FStar.UInt32", "module GA = Pulse.Lib.GlobalArray", ""]
    for a in used(t):
        rs = t["arrays"][a]
        n = 2 * len(rs)
        o.append("let l_%s : list U32.t = [%s]" % (a, "; ".join("%dul; %dul" % r for r in rs)))
        o.append("let cr_%s : GA.static_array U32.t = GA.mk_static_array l_%s" % (a, a))
        o.append("let len_%s : n:US.t{US.v n == List.Tot.length l_%s} = assert_norm (List.Tot.length l_%s == %d); %dsz" % (a, a, a, n, n))
    o.append("""
fn mem_arr (l:US.t) (a: array U32.t) (#p:perm) (#s: Ghost.erased (Seq.seq U32.t)) (c: U32.t)
  requires pts_to a #p s ** pure (US.v l == Seq.length s /\\ US.v l < 60000)
  returns res: bool
  ensures emp
{
  let mut i = 0sz;
  while (let vi = !i; if (US.lt (US.add vi 1sz) l) { U32.lt (a.(US.add vi 1sz)) c } else { false })
  invariant exists* (vi:US.t). (pts_to i vi ** pts_to a #p s ** pure (US.v vi <= US.v l + 1))
  decreases (US.v l + 1 - US.v !i)
  {
    let vi = !i;
    i := US.add vi 2sz;
  };
  let vi = !i;
  if (US.lt (US.add vi 1sz) l) {
    let lo = a.(vi);
    drop_ (pts_to a #p s);
    U32.lte lo c
  } else {
    drop_ (pts_to a #p s);
    false
  }
}
""")
    for a in used(t):
        o.append("fn mem_%s (c: U32.t)\n  requires emp\n  returns res: bool\n  ensures emp\n{\n  let a = GA.array_of_static_array cr_%s;\n  mem_arr len_%s a c\n}\n" % (a, a, a))
    cr = t["code_ranges"]
    def disp(lo, hi, ind):
        if hi - lo == 1:
            return "mem_%s c" % cr[lo]
        m = (lo + hi) // 2
        return "if (U32.lt ct %dul) {\n%s%s\n%s} else {\n%s%s\n%s}" % (
            m, ind + "  ", disp(lo, m, ind + "  "), ind, ind + "  ", disp(m, hi, ind + "  "), ind)
    o.append("fn ctype_mem (ct: U32.t) (c: U32.t)\n  requires emp\n  returns res: bool\n  ensures emp\n{\n  if (U32.lt ct %dul) {\n    %s\n  } else {\n    false\n  }\n}" % (len(cr), disp(0, len(cr), "    ")))
    return "\n".join(o) + "\n"

def main():
    src, out = sys.argv[1], sys.argv[2]
    t = parse(src)
    if "--limit" in sys.argv:
        n = int(sys.argv[sys.argv.index("--limit") + 1])
        t["code_ranges"] = t["code_ranges"][:n]
        t["names"] = [(a, c) for a, c in t["names"] if c < n]
    os.makedirs(out, exist_ok=True)
    files = {"table.json": json.dumps({k: t[k] for k in ("order", "code_ranges", "names", "aliases")} |
                                      {"arrays": t["arrays"]}),
             "rocq/Table.v": rocq(t), "lean/Table.lean": lean(t),
             "why3/table.mlw": why3(t), "why3/tablec.mlw": why3c(t),
             "fstar/Table.fst": fstar(t), "fstar/TableC.fst": fstarc(t),
             "fstar/PulseTable.fst": pulse(t)}
    rows = []
    for f, c in files.items():
        p = os.path.join(out, f)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(c)
        rows.append("%s\t%d\t%s" % (f, len(c.encode()), hashlib.sha256(c.encode()).hexdigest()))
    open(os.path.join(out, "emitted.tsv"), "w").write("\n".join(rows) + "\n")
    print("\n".join(rows))

if __name__ == "__main__":
    main()
