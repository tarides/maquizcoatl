(* Experiment #6, milestone 2, Rocq: executable semantics of experiment
   #1's first subset S2 of Oniguruma f95747b, transcribed from stack G
   (lab/06-spec-speed/g/g2.ml) into milestone 1's small-step machine
   (rocq/Spec.v), as fstar/Spec2.fst and why3/spec2.mlw: pending items
   plus an explicit list of backtracking points, one machine step per
   call of [step]; fuel is a positive, iterated by halving, so that
   10,000,000 costs no unary number.  Commit points (atomic groups,
   possessive quantifiers, lookaround bodies) are items that carry the
   backtracking list to restore.  The case-fold map and the property
   ranges come from the table module [Tables] (generated by
   cases/gen2.py), so that T_spec measures the semantics alone.
   Positions and group numbers are [nat] (extracted with
   ExtrOcamlNatInt), bytes, code points and repetition counts are [N].
   No type indices or proofs in executable definitions. *)

From Stdlib Require Import List NArith PArith Bool Arith.
From S Require Import Tables.
Import ListNotations.

Inductive cset : Type :=
| CR (lo hi : N)
| CP (p : N)
| CNot (s : cset)
| COr (l : list cset)
| CAnd (a b : cset).

Inductive anchor : Type :=
| BolA | EolA | BufBeg | BufEnd | SemiEnd | SearchStart | WordB | NotWordB.

Inductive node : Type :=
| Eps
| Lit (bs : list N)
| LitI (f : list N)                              (* folded pattern string *)
| Cls (s : cset)
| ClsI (s : cset) (ms : list (list N))
| Cat (a b : node)
| Alt (a b : node)
| Rep (mn : N) (mx : option N) (g : bool) (a : node)   (* mx None: infinite *)
| Atomic (a : node)
| Ahead (neg : bool) (a : node)
| Behind (neg : bool) (alts : list node)
| Group (k : nat) (a : node)
| Bref (gs : list nat) (ic : bool)
| Anc (a : anchor).

Definition caps := list (nat * (nat * nat)).

(* backtracking point: items, position, rest of the subject, captures *)
Inductive item : Type :=
| INode (n : node)
| IClose (k : nat) (p : nat)
| IIter (mn : N) (mx : option N) (g : bool) (a : node) (c : N) (p0 : nat) (c0 : caps)
| ICut (bt : list (list item * nat * list N * caps))
| ILookOk (bt : list (list item * nat * list N * caps)) (p : nat) (r : list N)
| INegFail (bt : list (list item * nat * list N * caps))
| IAtEnd (i : nat)
| IBTry (alts : list node) (j : nat) (i : nat).

Definition frame := (list item * nat * list N * caps)%type.

Inductive state : Type :=
| Run (its : list item) (pos : nat) (rest : list N) (cs : caps) (bt : list frame)
| Matched (pos : nat) (cs : caps)
| Failed.

(* UTF-8, as upstream/src/utf8.c (EncLen_UTF8, USE_RFC3629_RANGE) *)
Definition enc_len (b : N) : nat :=
  if (b <? 194)%N then 1 else if (b <? 224)%N then 2
  else if (b <? 240)%N then 3 else if (b <? 245)%N then 4 else 1.

Fixpoint take (n : nat) (l : list N) : option (list N * list N) :=
  match n with
  | O => Some ([], l)
  | S m => match l with
           | [] => None
           | x :: t => match take m t with
                       | Some (a, r) => Some (x :: a, r)
                       | None => None
                       end
           end
  end.

Definition lead_mod (l : nat) : N :=
  match l with 2 => 32%N | 3 => 16%N | _ => 8%N end.

(* code point, encoded length, rest; None past the end (DATA_ENSURE) *)
Definition decode (rest : list N) : option (N * nat * list N) :=
  match rest with
  | [] => None
  | b :: t =>
    let l := enc_len b in
    match l with
    | 1 => Some (b, 1, t)
    | _ => match take (l - 1) t with
           | Some (tl, r) =>
             Some (fold_left (fun v d => (v * 64 + N.modulo d 64)%N) tl
                             (N.modulo b (lead_mod l)), l, r)
           | None => None
           end
    end
  end.

Fixpoint prefix (l rest : list N) : option (list N) :=
  match l, rest with
  | [], _ => Some rest
  | x :: l', y :: r => if N.eqb x y then prefix l' r else None
  | _, [] => None
  end.

Fixpoint in_cset (c : N) (s : cset) : bool :=
  match s with
  | CR lo hi => (lo <=? c)%N && (c <=? hi)%N
  | CP p => in_prop p c
  | CNot s' => negb (in_cset c s')
  | COr l => (fix go (l : list cset) : bool :=
                match l with [] => false | x :: t => in_cset c x || go t end) l
  | CAnd a b => in_cset c a && in_cset c b
  end.

(* the remainder of [f] once [p] is stripped from its front *)
Fixpoint strip (p f : list N) : option (list N) :=
  match p, f with
  | [], _ => Some f
  | x :: p', y :: f' => if N.eqb x y then strip p' f' else None
  | _, [] => None
  end.

(* a subject segment whose full case fold is exactly [f]: rest after it *)
Fixpoint match_fold (rest : list N) (n : nat) (f : list N) : option (list N) :=
  match f with
  | [] => Some rest
  | _ =>
    match n with
    | O => None
    | S n' =>
      match decode rest with
      | None => None
      | Some (c, _, r) =>
        match strip (fold_of c) f with
        | Some f' => match_fold r n' f'
        | None => None
        end
      end
    end
  end.

Fixpoint fold_string (l : list N) (n : nat) (acc : list N) : list N :=
  match n with
  | O => acc
  | S n' =>
    match decode l with
    | None => acc
    | Some (c, _, r) => fold_string r n' (acc ++ fold_of c)
    end
  end.

Fixpoint set_cap (k : nat) (v : nat * nat) (cs : caps) : caps :=
  match cs with
  | [] => [(k, v)]
  | (k', w) :: t => if Nat.eqb k' k then (k, v) :: t else (k', w) :: set_cap k v t
  end.

Fixpoint lookup (k : nat) (cs : caps) : option (nat * nat) :=
  match cs with
  | [] => None
  | (k', v) :: t => if Nat.eqb k k' then Some v else lookup k t
  end.

Definition opt_eqb (a b : option (nat * nat)) : bool :=
  match a, b with
  | None, None => true
  | Some (x, y), Some (x', y') => Nat.eqb x x' && Nat.eqb y y'
  | _, _ => false
  end.

Fixpoint same_refs (refs : list nat) (a b : caps) : bool :=
  match refs with
  | [] => true
  | g :: t => opt_eqb (lookup g a) (lookup g b) && same_refs t a b
  end.

(* start of the character before [pos], or None *)
Fixpoint prev_from (l : list N) (i pos : nat) (last : option nat) : option nat :=
  if Nat.leb pos i then last
  else match l with
       | [] => last
       | b :: t =>
         prev_from t (S i) pos
                   (if (128 <=? b)%N && (b <? 192)%N then last else Some i)
       end.

Definition prev_pos (s : list N) (pos : nat) : option nat := prev_from s 0 pos None.

Definition word_at (rest : list N) : bool :=
  match decode rest with Some (c, _, _) => in_prop 12 c | None => false end.

Definition word_before (s : list N) (pos : nat) : bool :=
  match prev_pos s pos with Some p => word_at (skipn p s) | None => false end.

Definition is_nl (l : list N) : bool :=
  match l with b :: _ => N.eqb b 10 | [] => false end.

Definition anchor_ok (s : list N) (ln : nat) (a : anchor) (pos : nat) (rest : list N) : bool :=
  match a with
  | BolA => Nat.eqb pos 0 || is_nl (skipn (pos - 1) s)
  | EolA => Nat.eqb pos ln || is_nl rest
  | BufBeg | SearchStart => Nat.eqb pos 0
  | BufEnd => Nat.eqb pos ln
  | SemiEnd => Nat.eqb pos ln || (Nat.eqb (S pos) ln && is_nl rest)
  | WordB => negb (Bool.eqb (word_before s pos) (word_at rest))
  | NotWordB => Bool.eqb (word_before s pos) (word_at rest)
  end.

Definition backtrack (bt : list frame) : state :=
  match bt with
  | [] => Failed
  | (its, pos, rest, cs) :: bt' => Run its pos rest cs bt'
  end.

(* the next iteration of a loop, or leaving it *)
Definition rep (mn : N) (mx : option N) (g : bool) (a : node) (c : N) (k : list item)
           (pos : nat) (rest : list N) (cs : caps) (bt : list frame) : state :=
  let again := INode a :: IIter mn mx g a (N.succ c) pos cs :: k in
  let at_max := match mx with Some m => (m <=? c)%N | None => false end in
  if (c <? mn)%N then Run again pos rest cs bt
  else if at_max then Run k pos rest cs bt
  else if g then Run again pos rest cs ((k, pos, rest, cs) :: bt)
  else Run k pos rest cs ((again, pos, rest, cs) :: bt).

(* backreference: the groups in order, the first one set and matching *)
Fixpoint bref (s : list N) (gs : list nat) (ic : bool) (cs : caps) (rest : list N)
  : option (list N) :=
  match gs with
  | [] => None
  | g :: t =>
    match lookup g cs with
    | None => bref s t ic cs rest
    | Some (x, y) =>
      let txt := firstn (y - x) (skipn x s) in
      let r := if ic then match_fold rest (length rest) (fold_string txt (length txt) [])
               else prefix txt rest in
      match r with
      | Some r' => Some r'
      | None => bref s t ic cs rest
      end
    end
  end.

Fixpoint clsi_alts (k : list item) (ln : nat) (cs : caps) (rest : list N)
         (ms : list (list N)) (bt : list frame) : list frame :=
  match ms with
  | [] => bt
  | m :: t =>
    match match_fold rest (length rest) m with
    | Some r => (k, ln - length r, r, cs) :: clsi_alts k ln cs rest t bt
    | None => clsi_alts k ln cs rest t bt
    end
  end.

Definition step (s : list N) (ln : nat) (refs : list nat) (st : state) : state :=
  match st with
  | Run its pos rest cs bt =>
    match its with
    | [] => Matched pos cs
    | INode Eps :: k => Run k pos rest cs bt
    | INode (Lit l) :: k =>
      match prefix l rest with
      | Some r => Run k (pos + length l) r cs bt
      | None => backtrack bt
      end
    | INode (LitI f) :: k =>
      match match_fold rest (length rest) f with
      | Some r => Run k (ln - length r) r cs bt
      | None => backtrack bt
      end
    | INode (Cls cl) :: k =>
      match decode rest with
      | Some (c, l, r) => if in_cset c cl then Run k (pos + l) r cs bt else backtrack bt
      | None => backtrack bt
      end
    | INode (ClsI cl ms) :: k =>
      let bt' := clsi_alts k ln cs rest ms bt in
      match decode rest with
      | Some (c, l, r) => if in_cset c cl then Run k (pos + l) r cs bt' else backtrack bt'
      | None => backtrack bt'
      end
    | INode (Cat a b) :: k => Run (INode a :: INode b :: k) pos rest cs bt
    | INode (Alt a b) :: k => Run (INode a :: k) pos rest cs ((INode b :: k, pos, rest, cs) :: bt)
    | INode (Rep mn mx g a) :: k => rep mn mx g a 0 k pos rest cs bt
    | IIter mn mx g a c p0 c0 :: k =>
      (* DEV-008: every loop, bounded or not, also below mn *)
      if Nat.eqb pos p0 && same_refs refs cs c0 then Run k pos rest cs bt
      else rep mn mx g a c k pos rest cs bt
    | INode (Atomic a) :: k => Run (INode a :: ICut bt :: k) pos rest cs bt
    | ICut bt0 :: k => Run k pos rest cs bt0
    | INode (Ahead ng a) :: k =>
      if ng then Run (INode a :: INegFail bt :: k) pos rest cs ((k, pos, rest, cs) :: bt)
      else Run (INode a :: ILookOk bt pos rest :: k) pos rest cs bt
    | ILookOk bt0 p r :: k => Run k p r cs bt0
    | INegFail bt0 :: _ => backtrack bt0
    | INode (Behind ng alts) :: k =>
      if ng then Run (IBTry alts pos pos :: INegFail bt :: k) pos rest cs ((k, pos, rest, cs) :: bt)
      else Run (IBTry alts pos pos :: ILookOk bt pos rest :: k) pos rest cs bt
    | IBTry alts j i :: k =>
      match alts with
      | [] => backtrack bt
      | a :: t =>
        let next := match prev_pos s j with
                    | Some p => IBTry alts p i :: k
                    | None => IBTry t i i :: k
                    end in
        Run (INode a :: IAtEnd i :: k) j (skipn j s) cs ((next, pos, rest, cs) :: bt)
      end
    | IAtEnd i :: k => if Nat.eqb pos i then Run k pos rest cs bt else backtrack bt
    | INode (Group i a) :: k => Run (INode a :: IClose i pos :: k) pos rest cs bt
    | IClose i p0 :: k => Run k pos rest (set_cap i (p0, pos) cs) bt
    | INode (Bref gs ic) :: k =>
      match bref s gs ic cs rest with
      | Some r => Run k (ln - length r) r cs bt
      | None => backtrack bt
      end
    | INode (Anc a) :: k =>
      if anchor_ok s ln a pos rest then Run k pos rest cs bt else backtrack bt
    end
  | _ => st
  end.

(* exactly p steps, or fewer if the machine stops *)
Fixpoint run (s : list N) (ln : nat) (refs : list nat) (p : positive) (st : state) : state :=
  match st with
  | Run _ _ _ _ _ =>
    match p with
    | xH => step s ln refs st
    | xO q => run s ln refs q (run s ln refs q st)
    | xI q => run s ln refs q (run s ln refs q (step s ln refs st))
    end
  | _ => st
  end.

Inductive result : Type :=
| RMatch (s e : nat) (cs : caps)
| RMismatch
| RLimit.

(* forward search: start positions 0..length, advanced by enc_len *)
Fixpoint search_from (s : list N) (ln : nat) (refs : list nat) (n : nat) (fuel : positive)
         (re : node) (pos : nat) (rest : list N) : result :=
  match n with
  | O => RMismatch
  | S n' =>
    match run s ln refs fuel (Run [INode re] pos rest [] []) with
    | Matched e cs => RMatch pos e cs
    | Run _ _ _ _ _ => RLimit
    | Failed =>
      match rest with
      | [] => RMismatch
      | b :: _ =>
        let l := enc_len b in
        match take l rest with
        | Some (_, r) => search_from s ln refs n' fuel re (pos + l) r
        | None => RMismatch
        end
      end
    end
  end.

Definition search (fuel : positive) (refs : list nat) (re : node) (s : list N) : result :=
  let ln := length s in search_from s ln refs (S ln) fuel re 0 s.

(* verdict as numbers: [0] no match, [2] limit, 1 :: s :: e :: groups,
   each group [1; s; e] or [0] when unset *)
Definition encode (ncap : nat) (r : result) : list nat :=
  match r with
  | RMismatch => [0]
  | RLimit => [2]
  | RMatch s e cs =>
    1 :: s :: e :: flat_map (fun k => match lookup k cs with
                                      | Some (x, y) => [1; x; y]
                                      | None => [0]
                                      end) (seq 1 ncap)
  end.

Definition fuel0 : positive := 10000000%positive.

Definition run_case (fuel : positive) (ncap : nat) (refs : list nat) (re : node) (s : list N)
  : list nat :=
  encode ncap (search fuel refs re s).

(* a case: groups, backreferenced groups, pattern, subject, expected *)
Definition case := (nat * list nat * node * list N * list nat)%type.

Fixpoint nat_list_eqb (a b : list nat) : bool :=
  match a, b with
  | [], [] => true
  | x :: a', y :: b' => Nat.eqb x y && nat_list_eqb a' b'
  | _, _ => false
  end.

Definition agree (fuel : positive) (c : case) : bool :=
  match c with
  | (ncap, refs, re, s, exp) => nat_list_eqb (run_case fuel ncap refs re s) exp
  end.

Definition count (fuel : positive) (cs : list case) : nat :=
  fold_left (fun acc c => if agree fuel c then S acc else acc) cs 0.

(* r passes; pass i uses fuel0 + i so that no pass can be shared *)
Fixpoint passes (r : nat) (cs : list case) (acc : nat) : nat :=
  match r with
  | O => acc
  | S r' => passes r' cs (acc + count (Pos.add fuel0 (Pos.of_succ_nat r')) cs)
  end.
