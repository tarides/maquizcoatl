#!/usr/bin/env python3
# Generate the criterion 3-5 tables from patterns/*.jsonl.
# Usage: tables.py PATTERNS_DIR TABLES_DIR   (prints a summary JSON on stdout)
import json, sys, pathlib, collections, csv

COLS = ['captures', 'named_groups', 'backreferences', 'lookahead', 'lookbehind',
        'atomic_groups', 'possessive', 'bounded_repetition', 'subexp_calls',
        'absent', 'conditionals', 'callouts', 'unicode_properties',
        'case_insensitive', 'multichar_casefold']
FUEL = ['backreferences', 'subexp_calls', 'absent', 'conditionals', 'callouts']
SOURCES = [('vscode', 'VS Code TextMate grammars (compiled form)'),
           ('vscode-grammar-text', 'VS Code TextMate grammars (grammar text, alongside)'),
           ('jq', 'jq (tests + manual)'),
           ('php', 'PHP mbregex (php-src tests + manual)')]
MAIN = ['vscode', 'jq', 'php']
OPTS = {1: 'IGNORECASE', 2: 'EXTEND', 4: 'MULTILINE', 8: 'SINGLELINE', 16: 'FIND_LONGEST',
        32: 'FIND_NOT_EMPTY', 256: 'CAPTURE_GROUP'}

def load(pdir, s):
    return [json.loads(l) for l in open(pdir / f'{s}.jsonl', encoding='utf-8')]

def pct(a, b):
    return f'{100.0 * a / b:.1f}%' if b else '-'

def tier(t):
    return 'fuel' if any(t['compile']['features'][c] for c in FUEL) else 'linear'

def subsets(ok):
    """Candidate first subsets: predicate over compiled triples."""
    f = lambda t, c: t['compile']['features'][c]
    base = lambda t: t['encoding'] == 'UTF-8' and t['syntax'] in ('ONIGURUMA', 'PERL_NG', 'RUBY')
    return {
        'S0: UTF-8; Oniguruma/Perl_NG/Ruby syntax; linear tier': lambda t: base(t) and tier(t) == 'linear',
        'S1: S0 without multi-character case folding': lambda t: base(t) and tier(t) == 'linear' and not f(t, 'multichar_casefold'),
        'S2: S0 + backreferences': lambda t: base(t) and not any(f(t, c) for c in FUEL if c != 'backreferences'),
        'S3: S2 + subexpression calls, conditionals (everything except absent and callouts)': lambda t: base(t) and not (f(t, 'absent') or f(t, 'callouts')),
    }

def main():
    pdir, tdir = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    tdir.mkdir(parents=True, exist_ok=True)
    data = {s: load(pdir, s) for s, _ in SOURCES}
    summary = {}
    md = ['# Pattern inventory tables (experiment #1)', '',
          'Generated by `scripts/tables.py` from `patterns/*.jsonl`. Unit: distinct',
          '(pattern, syntax, options, encoding) triple. "occ." columns weight each',
          'triple by its number of occurrences in the corpus. Shares are over the',
          'triples that compile with upstream `f95747b`.', '',
          '**Bias.** Decision (a) limits jq and PHP to the hosts\' own repositories',
          '(test suites and manuals). These exercise edge cases more than typical',
          'use and under-represent real-world jq and PHP patterns. Sources are',
          'reported separately and never pooled silently.', '']
    feat_rows = []
    for s, title in SOURCES:
        ts = data[s]
        ok = [t for t in ts if t['compile']['status'] == 'ok']
        bad = [t for t in ts if t['compile']['status'] != 'ok']
        n, nocc = len(ok), sum(t['occurrences'] for t in ok)
        md += [f'## {title}', '',
               f'{len(ts)} distinct triples ({sum(t["occurrences"] for t in ts)} occurrences); '
               f'{n} compile, {len(bad)} fail ({", ".join(f"{k}: {v}" for k, v in collections.Counter(t["compile"]["status"] for t in bad).items()) or "none"}).', '',
               '| Feature | triples | share | occ. share |', '|---|---:|---:|---:|']
        fs = {}
        for c in COLS:
            k = sum(1 for t in ok if t['compile']['features'][c])
            ko = sum(t['occurrences'] for t in ok if t['compile']['features'][c])
            fs[c] = k
            md.append(f'| {c.replace("_", " ")} | {k} | {pct(k, n)} | {pct(ko, nocc)} |')
            feat_rows.append({'source': s, 'feature': c, 'triples': k, 'compiled': n,
                              'share': round(k / n, 4) if n else None,
                              'occ_share': round(ko / nocc, 4) if nocc else None})
        syn = collections.Counter(t['syntax'] for t in ts)
        enc = collections.Counter(t['encoding'] for t in ts)
        opt = collections.Counter('|'.join(v for b, v in OPTS.items() if t['options'] & b) or 'NONE' for t in ts)
        md += ['', '| Syntax | triples |', '|---|---:|'] + [f'| {k} | {v} |' for k, v in syn.most_common()]
        md += ['', '| Encoding | triples |', '|---|---:|'] + [f'| {k} | {v} |' for k, v in enc.most_common()]
        md += ['', '| Compile options | triples |', '|---|---:|'] + [f'| {k} | {v} |' for k, v in opt.most_common()]
        tiers = collections.Counter(tier(t) for t in ok)
        tiers_occ = collections.Counter()
        for t in ok: tiers_occ[tier(t)] += t['occurrences']
        md += ['', '| ReDoS tier | triples | share | occ. share |', '|---|---:|---:|---:|']
        for k in ('linear', 'fuel'):
            md.append(f'| {k} | {tiers[k]} | {pct(tiers[k], n)} | {pct(tiers_occ[k], nocc)} |')
        md.append(f'| (compile failure, apart) | {len(bad)} | | |')
        if bad:
            md += ['', '<details><summary>Compile failures</summary>', '', '| code | message | pattern | first seen |', '|---|---|---|---|']
            for t in bad:
                p = t['pattern'].replace('|', '\\|').replace('`', "'")[:60]
                md.append(f'| {t["compile"]["code"]} | {t["compile"]["message"]} | `{p}` | {t["first_seen"]} |')
            md += ['', '</details>']
        md.append('')
        summary[s] = {'triples': len(ts), 'compiled': n, 'failed': len(bad),
                      'features': fs, 'tiers': dict(tiers), 'tiers_occ': dict(tiers_occ),
                      'syntax': dict(syn), 'encoding': dict(enc)}
    # Overall over the three main sources (vscode compiled form).
    allok = [t for s in MAIN for t in data[s] if t['compile']['status'] == 'ok']
    n = len(allok)
    tiers = collections.Counter(tier(t) for t in allok)
    md += ['## ReDoS tiers, per source and overall', '',
           'Fuel tier: any of backreferences, subexpression calls, absent operator,',
           'conditionals, callouts. Linear tier: everything else (regular core,',
           'lookarounds, atomic groups, possessive and bounded repetition).', '',
           '| Source | compiled | linear | fuel |', '|---|---:|---:|---:|']
    for s in MAIN:
        x = summary[s]
        md.append(f'| {s} | {x["compiled"]} | {x["tiers"].get("linear", 0)} ({pct(x["tiers"].get("linear", 0), x["compiled"])}) | {x["tiers"].get("fuel", 0)} ({pct(x["tiers"].get("fuel", 0), x["compiled"])}) |')
    md.append(f'| overall (pooled triples) | {n} | {tiers["linear"]} ({pct(tiers["linear"], n)}) | {tiers["fuel"]} ({pct(tiers["fuel"], n)}) |')
    macro_lin = sum(summary[s]['tiers'].get('linear', 0) / summary[s]['compiled'] for s in MAIN) / len(MAIN)
    md.append(f'| overall (mean of per-source shares) | | {100 * macro_lin:.1f}% | {100 * (1 - macro_lin):.1f}% |')
    md += ['', 'The pooled row is dominated by VS Code (it holds '
           f'{pct(summary["vscode"]["compiled"], n)} of the compiled triples); the mean of',
           'per-source shares gives each host equal weight.', '']
    # Fuel breakdown
    md += ['### What puts a triple in the fuel tier', '', '| Source | ' + ' | '.join(FUEL) + ' |',
           '|---|' + '---:|' * len(FUEL)]
    for s in MAIN:
        md.append(f'| {s} | ' + ' | '.join(str(summary[s]['features'][c]) for c in FUEL) + ' |')
    md.append('')
    # Subsets
    md += ['## Candidate first subsets', '',
           'Share of the triples that compile which each subset covers (count in parentheses).', '',
           '| Subset | ' + ' | '.join(MAIN) + ' | pooled |', '|---|' + '---:|' * (len(MAIN) + 1)]
    sub = {}
    for name, pred in subsets(allok).items():
        row, sub[name] = [], {}
        for s in MAIN:
            ok = [t for t in data[s] if t['compile']['status'] == 'ok']
            k = sum(1 for t in ok if pred(t))
            sub[name][s] = (k, len(ok), len(data[s]))
            row.append(f'{pct(k, len(ok))} ({k}/{len(ok)})')
        k = sum(1 for t in allok if pred(t))
        sub[name]['pooled'] = (k, n, sum(len(data[s]) for s in MAIN))
        row.append(f'{pct(k, n)}')
        md.append(f'| {name} | ' + ' | '.join(row) + ' |')
    md.append('')
    # Deferral
    md += ['## Deferring subexpression calls, pattern callouts, absent operator', '',
           '| Feature | ' + ' | '.join(MAIN) + ' | pooled |', '|---|' + '---:|' * (len(MAIN) + 1)]
    for c in ('subexp_calls', 'callouts', 'absent', 'conditionals'):
        k = sum(1 for t in allok if t['compile']['features'][c])
        md.append(f'| {c} | ' + ' | '.join(f'{summary[s]["features"][c]} ({pct(summary[s]["features"][c], summary[s]["compiled"])})' for s in MAIN) + f' | {k} ({pct(k, n)}) |')
    md.append('')
    md += ['Files (VS Code grammars, jq test/manual files, PHP test files) containing at least one',
           'triple with the feature; a grammar with one unsupported pattern cannot be fully tokenised.', '',
           '| Feature | ' + ' | '.join(MAIN) + ' |', '|---|' + '---:|' * len(MAIN)]
    for c in ('subexp_calls', 'callouts', 'absent', 'conditionals', 'backreferences', 'multichar_casefold'):
        cells = []
        for s in MAIN:
            allf = {f for t in data[s] for f in t['files']}
            hit = {f for t in data[s] if t['compile']['status'] == 'ok' and t['compile']['features'][c] for f in t['files']}
            cells.append(f'{len(hit)}/{len(allf)}' + (f' ({", ".join(sorted({h.split("/")[1] if s == "vscode" else h.rsplit("/", 1)[-1] for h in hit}))})' if hit and len(hit) <= 20 else ''))
        md.append(f'| {c} | ' + ' | '.join(cells) + ' |')
    md.append('')
    # Dynamic-only triples (seen at run time, not in the static corpus).
    dyn = {s: load(pdir, f'{s}.dynamic-only') for s in MAIN if (pdir / f'{s}.dynamic-only.jsonl').exists()}
    if dyn:
        md += ['## Dynamic-only triples', '',
               'Triples compiled at run time (workload capture) that the static extraction',
               'did not produce: computed or interpolated patterns (jq, PHP), and for VS Code',
               'the scanner variants in which vscode-textmate replaced `\\A`/`\\G` by U+FFFF or',
               'substituted `begin` captures into `end`/`while`. Not included in the tables above.', '',
               '| Source | triples | compile | ' + ' | '.join(c.replace('_', ' ') for c in COLS) + ' | fuel tier |',
               '|---|---:|---:|' + '---:|' * (len(COLS) + 1)]
        for s, ts in dyn.items():
            ok = [t for t in ts if t['compile']['status'] == 'ok']
            md.append(f'| {s} | {len(ts)} | {len(ok)} | ' +
                      ' | '.join(str(sum(1 for t in ok if t['compile']['features'][c])) for c in COLS) +
                      f' | {sum(1 for t in ok if tier(t) == "fuel")} |')
            summary[f'{s}-dynamic-only'] = {'triples': len(ts), 'compiled': len(ok)}
        md.append('')
    (tdir / 'tables.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    with open(tdir / 'features.csv', 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=['source', 'feature', 'triples', 'compiled', 'share', 'occ_share'])
        w.writeheader(); w.writerows(feat_rows)
    summary['subsets'] = sub
    json.dump(summary, sys.stdout, indent=1)
    print()

main()
