#!/usr/bin/env python3
"""gen_isabelle_stub.py AUX AUXP SYMBOLS.tsv OUTDIR

Mechanism 4 stub (Isabelle-LLVM), generated mechanically from the
public headers, like mechanism 2's gen_c_stub.py (same inputs: the
`gcc -aux-info` outputs AUX for oniggnu.h and AUXP for onigposix.h,
and symbols.tsv).

Isabelle-LLVM's export_llvm accepts C signatures over a small type
language only (thys/basic/kernel/LLVM_Codegen.thy, parse_cprim and
parse_ctype at commit e42f4781): char, int8_t..int64_t, uint8_t..uint64_t,
float, double, pointers and named struct/union typedefs. No `int`,
`unsigned`, `size_t`, `const`, enum, function-pointer type or `...`.
So every public C type is mapped to an ABI-equivalent type on x86-64
LP64 (System V):

  int, enum types                          -> int32_t   (32 word)
  unsigned int and its typedefs            -> uint32_t  (32 word)
  size_t, long unsigned int                -> uint64_t  (64 word)
  any pointer, pointer typedef, array
  parameter or function pointer            -> uint8_t*  (8 word ptr)

LLVM IR has opaque pointers, so a function pointer and a data pointer
are the same `ptr` there. The mapping is checked by sizes.c
(_Static_assert on each C type), written next to the theories.

Every function body returns a fixed value (0, null, or unit). The
variadic onig_error_code_to_str cannot be expressed (no `...` in the
signature grammar, no va_arg in the semantics) and stays in mechanism
2's hand-written stub_shell.c. Isabelle-LLVM has no global data
definitions, so the 44 public data symbols (encoding structs holding
function pointers, syntax structs, OnigDefaultSyntax pointing to
another global, OnigDefaultCaseFoldFlag) are emitted as C in shell_data.c,
outside the proofs.

Writes OUTDIR/OnigStub.thy (default API), OUTDIR/OnigStubPosix.thy
(the 8 onig_posix_* functions), OUTDIR/ROOT, OUTDIR/shell_data.c,
OUTDIR/sizes.c and OUTDIR/mapping.tsv (function, C prototype, exported
signature).
"""
import re, sys

aux, auxp, symf, outdir = sys.argv[1:5]
HANDWRITTEN = {"onig_error_code_to_str"}

syms = {}
for l in open(symf).read().splitlines()[1:]:
    n, k, c, where, builds = l.split("\t")
    syms[n] = (k, c, builds)

PROTO = re.compile(r"/\* (\S+?):(\d+):\w+ \*/ extern (.*?)\b(\w+) \((.*)\);$")

def protos(f):
    d = {}
    for l in open(f):
        m = PROTO.search(l.strip())
        if m and m.group(1).split("/")[-1].startswith("onig"):
            d[m.group(4)] = (m.group(3).strip(), m.group(5), m.group(1).split("/")[-1], m.group(2))
    return d

def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

PTR_TYPEDEFS = {"OnigEncoding", "OnigRegex", "OnigCallbackEachMatchFunc",
                "OnigCalloutFunc", "OnigWarnFunc"}
I32 = {"int", "OnigCalloutType", "OnigRegSetLead", "OnigType", "OnigCalloutIn"}
U32 = {"unsigned int", "OnigCodePoint", "OnigCaseFoldType", "OnigOptionType"}
U64 = {"size_t", "long unsigned int"}
# (C name, Isabelle type, zero value)
T_PTR = ("uint8_t*", "8 word ptr", "null")
T_I32 = ("int32_t", "32 word", "0")
T_U32 = ("uint32_t", "32 word", "0")
T_U64 = ("uint64_t", "64 word", "0")
seen_types = {}

def map_type(t):
    if "*" in t or "[" in t:
        return T_PTR
    b = re.sub(r"\b(const|volatile)\b", "", t).strip()
    b = re.sub(r"\s+", " ", b)
    for s, m in ((PTR_TYPEDEFS, T_PTR), (I32, T_I32), (U32, T_U32), (U64, T_U64)):
        if b in s:
            seen_types[b] = m[0]
            return m
    raise SystemExit(f"unmapped C type: {t!r}")

def thy_name(n):
    return "c_" + n

def entry(name, ret, params):
    ps = split_params(params)
    if ps == ["void"]:
        ps = []
    if "..." in ps:
        raise SystemExit(f"variadic {name} must be hand-written")
    args = [map_type(p) for p in ps]
    r = None if ret == "void" else map_type(ret)
    ity = " \\<Rightarrow> ".join([a[1] for a in args] +
                                  [f"{'unit' if r is None else r[1]} llM"])
    vs = " ".join(f"p{i}" for i in range(len(args)))
    body = "Mreturn ()" if r is None else f"Mreturn {r[2]}"
    lhs = f"{thy_name(name)} {vs}".strip()
    defn = (f'definition {thy_name(name)} :: "{ity}" where [llvm_code]:\n'
            f'  "{lhs} \\<equiv> {body}"\n\n')
    csig = f"{'void' if r is None else r[0]} {name} ({', '.join(a[0] for a in args)})"
    return defn, csig

def theory(path, tname, funcs, wanted, build, mapping, proof):
    exports = []
    with open(path, "w") as o:
        o.write(f"(* Generated by gen_isabelle_stub.py: do not edit. *)\n"
                f"theory {tname}\n  imports Isabelle_LLVM.LLVM_DS_All\nbegin\n\n")
        for n in sorted(wanted):
            k, c, builds = syms[n]
            if k != "F" or c != "public" or build not in builds or n in HANDWRITTEN:
                continue
            if n not in funcs:
                raise SystemExit(f"no prototype for {n}")
            ret, params, h, line = funcs[n]
            defn, csig = entry(n, ret, params)
            o.write(f"(* {h}:{line} *)\n" + defn)
            exports.append((n, csig))
            mapping.append(f"{n}\t{ret} {n}({params})\t{csig}")
        o.write(proof)
        o.write("export_llvm\n")
        for n, csig in exports:
            o.write(f'  {thy_name(n)} is "{csig}"\n')
        o.write(f'  file "{tname}.ll"\n\nend\n')
    return len(exports)

# One VCG proof, to show the exported code lives inside Isabelle-LLVM's
# semantics: onig_end returns 0 (upstream/src/regcomp.c onig_end returns
# ONIG_NORMAL).
PROOF = r'''(* One Hoare triple over the exported code, as in experiment #5's
   smoke test: the stub's onig_end returns ONIG_NORMAL (0). *)
lemma c_onig_end_correct:
  "llvm_htriple \<box> c_onig_end (\<lambda>r. \<up>(r = 0))"
  unfolding c_onig_end_def
  apply vcg_monadify
  apply vcg'
  done

'''

main = protos(aux)
posix = protos(auxp)
mapping = ["function\tC prototype (aux-info)\texported signature (export_llvm)"]
nd = theory(f"{outdir}/OnigStub.thy", "OnigStub", main, list(syms), "default", mapping, PROOF)
np = theory(f"{outdir}/OnigStubPosix.thy", "OnigStubPosix", posix,
            [n for n in syms if n.startswith("onig_posix_")], "posix", mapping, "")
with open(f"{outdir}/mapping.tsv", "w") as o:
    o.write("\n".join(mapping) + "\n")
with open(f"{outdir}/ROOT", "w") as o:
    o.write("session Onig_Stub_M4 = Isabelle_LLVM +\n  theories OnigStub OnigStubPosix\n")

# sizes.c: the type mapping checked against the real C types.
with open(f"{outdir}/sizes.c", "w") as o:
    o.write('/* Generated by gen_isabelle_stub.py: checks the C type mapping. */\n'
            '#include <stddef.h>\n#include <stdint.h>\n#include "oniguruma.h"\n')
    for b, ct in sorted(seen_types.items()):
        o.write(f"_Static_assert(sizeof({b}) == sizeof({ct}), \"{b}\");\n")
        o.write(f"_Static_assert(_Alignof({b}) == _Alignof({ct}), \"{b} align\");\n")

# shell_data.c: the data symbols, as in mechanism 2 (gen_c_stub.py).
with open(f"{outdir}/shell_data.c", "w") as o:
    o.write("/* Generated by gen_isabelle_stub.py: do not edit. Data symbols of the\n"
            "   mechanism 4 stub, outside the proofs: Isabelle-LLVM has no global\n"
            "   data definitions. Same initialisers as mechanism 2. */\n"
            '#include "oniggnu.h"\n#include "stub_data.h"\n\n')
    nd_data = 0
    for n in sorted(syms):
        k, c, builds = syms[n]
        if k != "D" or c != "public":
            continue
        nd_data += 1
        if n.startswith("OnigEncoding"):
            o.write(f'OnigEncodingType {n} = STUB_ENCODING("{n[12:]}");\n')
        elif n.startswith("OnigSyntax"):
            o.write(f"OnigSyntaxType {n} = STUB_SYNTAX;\n")
        elif n == "OnigDefaultSyntax":
            o.write("OnigSyntaxType* OnigDefaultSyntax = &OnigSyntaxOniguruma;\n")
        elif n == "OnigDefaultCaseFoldFlag":
            o.write("OnigCaseFoldType OnigDefaultCaseFoldFlag = ONIGENC_CASE_FOLD_MIN;\n")
        else:
            raise SystemExit(f"unhandled data symbol {n}")
print(f"functions exported by Isabelle-LLVM: default {nd}, posix {np}; "
      f"hand-written C: {len(HANDWRITTEN)} variadic, {nd_data} data symbols; "
      f"C types mapped: {', '.join(f'{b}->{c}' for b, c in sorted(seen_types.items()))}")
