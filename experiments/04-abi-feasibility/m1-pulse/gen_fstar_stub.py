#!/usr/bin/env python3
"""gen_fstar_stub.py AUX AUXP SYMBOLS.tsv OUT.fst [posix]

Mechanism 1: the libonig stub as one F* module (OnigStub), generated from
the `gcc -aux-info` prototypes of the public headers, for extraction by
both emitters (1a KaRaMeL, 1b Custard). Per public function exported by
the oracle, a Pulse function (requires emp, ensures emp) returning a fixed
value; per public data
symbol, a top-level value carrying `rename_let "<exact C name>"`.

Types: C int and enums -> Int32, unsigned/OnigCodePoint/... -> UInt32,
size_t -> SizeT, unsigned long -> UInt64, every data or function pointer
parameter or result -> Pulse.Lib.Reference.ref UInt8 (a C pointer; results
are Pulse.Lib.Reference.null). The struct of an encoding keeps its 16
function pointers with their arities. Not generated (no F* counterpart):
the variadic onig_error_code_to_str, and OnigDefaultSyntax, a pointer to
another global (F* has no address-of on globals); both live in the
hand-written C shell.
"""
import re, sys

aux, auxp, symf, out = sys.argv[1:5]
posix = len(sys.argv) > 5 and sys.argv[5] == "posix"
SKIP = {"onig_error_code_to_str"}
PROTO = re.compile(r"/\* (\S+?):(\d+):\w+ \*/ extern (.*?)\b(\w+) \((.*)\);$")
UINT = {"unsigned int", "OnigCodePoint", "OnigOptionType", "OnigCaseFoldType"}
INT = {"int", "OnigCalloutIn", "OnigCalloutType", "OnigRegSetLead", "OnigType"}
PTR_TYPEDEFS = {"OnigEncoding", "OnigRegex", "OnigCalloutFunc", "OnigWarnFunc",
                "OnigCallbackEachMatchFunc"}

def fty(t):
    t = t.strip()
    if t == "void":
        return None
    if "*" in t or "(" in t or t in PTR_TYPEDEFS:
        return "ptr"
    if t in UINT:
        return "U32.t"
    if t in INT:
        return "I32.t"
    if t == "size_t":
        return "US.t"
    if t == "long unsigned int":
        return "U64.t"
    raise SystemExit(f"unmapped C type: {t!r}")

ZERO = {"U32.t": "0ul", "I32.t": "0l", "US.t": "0sz", "U64.t": "0uL",
        "ptr": "R.null #U8.t"}

def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

syms = {}
for l in open(symf).read().splitlines()[1:]:
    n, k, c, where, builds = l.split("\t")
    syms[n] = (k, c, builds)
protos = {}
for f in (aux, auxp):
    for l in open(f):
        m = PROTO.search(l.strip())
        if m and m.group(1).split("/")[-1].startswith("onig"):
            protos[m.group(4)] = (m.group(3), m.group(5), m.group(1).split("/")[-1], m.group(2))

o = open(out, "w")
o.write("""(* Generated by gen_fstar_stub.py: do not edit. *)
module OnigStub
#lang-pulse
open Pulse.Lib.Pervasives
module R = Pulse.Lib.Reference
module U8 = FStar.UInt8
module U32 = FStar.UInt32
module U64 = FStar.UInt64
module I32 = FStar.Int32
module US = FStar.SizeT

type ptr = R.ref U8.t

(* OnigEncodingType (upstream/src/oniguruma.h:130-153), field for field *)
noeq type onig_encoding_type = {
  mbc_enc_len : ptr -> I32.t;
  name : ptr;
  max_enc_len : I32.t;
  min_enc_len : I32.t;
  is_mbc_newline : ptr -> ptr -> I32.t;
  mbc_to_code : ptr -> ptr -> U32.t;
  code_to_mbclen : U32.t -> I32.t;
  code_to_mbc : U32.t -> ptr -> I32.t;
  mbc_case_fold : U32.t -> ptr -> ptr -> ptr -> I32.t;
  apply_all_case_fold : U32.t -> ptr -> ptr -> I32.t;
  get_case_fold_codes_by_str : U32.t -> ptr -> ptr -> ptr -> I32.t;
  property_name_to_ctype : ptr -> ptr -> ptr -> I32.t;
  is_code_ctype : U32.t -> U32.t -> I32.t;
  get_ctype_code_range : U32.t -> ptr -> ptr -> I32.t;
  left_adjust_char_head : ptr -> ptr -> ptr;
  is_allowed_reverse_match : ptr -> ptr -> I32.t;
  init : unit -> I32.t;
  is_initialized : unit -> I32.t;
  is_valid_mbc_string : ptr -> ptr -> I32.t;
  flag : U32.t;
  sb_range : U32.t;
  index : I32.t;
}

(* OnigMetaCharTableType and OnigSyntaxType (oniguruma.h:119-126,413-419) *)
type onig_meta_char_table_type = {
  esc : U32.t; anychar : U32.t; anytime : U32.t;
  zero_or_one_time : U32.t; one_or_more_time : U32.t; anychar_anytime : U32.t;
}
type onig_syntax_type = {
  op : U32.t; op2 : U32.t; behavior : U32.t; options : U32.t;
  meta_char_table : onig_meta_char_table_type;
}

let s_mbc_enc_len (p: ptr) : I32.t = 1l
let s_is_mbc_newline (p e: ptr) : I32.t = 0l
let s_mbc_to_code (p e: ptr) : U32.t = 0ul
let s_code_to_mbclen (c: U32.t) : I32.t = 1l
let s_code_to_mbc (c: U32.t) (b: ptr) : I32.t = 1l
let s_mbc_case_fold (f: U32.t) (pp e t: ptr) : I32.t = 1l
let s_apply_all_case_fold (f: U32.t) (g a: ptr) : I32.t = 0l
let s_get_case_fold_codes_by_str (f: U32.t) (p e a: ptr) : I32.t = 0l
let s_property_name_to_ctype (n p e: ptr) : I32.t = (-223l)
let s_is_code_ctype (c t: U32.t) : I32.t = 0l
let s_get_ctype_code_range (t: U32.t) (sb r: ptr) : I32.t = (-2l)
let s_left_adjust_char_head (s p: ptr) : ptr = p
let s_is_allowed_reverse_match (p e: ptr) : I32.t = 1l
let s_init () : I32.t = 0l
let s_is_initialized () : I32.t = 1l
let s_is_valid_mbc_string (s e: ptr) : I32.t = 1l

""")

ENC_LIT = """{
  mbc_enc_len = s_mbc_enc_len; name = R.null #U8.t; max_enc_len = 1l; min_enc_len = 1l;
  is_mbc_newline = s_is_mbc_newline; mbc_to_code = s_mbc_to_code;
  code_to_mbclen = s_code_to_mbclen; code_to_mbc = s_code_to_mbc;
  mbc_case_fold = s_mbc_case_fold; apply_all_case_fold = s_apply_all_case_fold;
  get_case_fold_codes_by_str = s_get_case_fold_codes_by_str;
  property_name_to_ctype = s_property_name_to_ctype; is_code_ctype = s_is_code_ctype;
  get_ctype_code_range = s_get_ctype_code_range; left_adjust_char_head = s_left_adjust_char_head;
  is_allowed_reverse_match = s_is_allowed_reverse_match; init = s_init;
  is_initialized = s_is_initialized; is_valid_mbc_string = s_is_valid_mbc_string;
  flag = 0ul; sb_range = 0ul; index = 0l;
}"""
SYN_LIT = """{
  op = 0ul; op2 = 0ul; behavior = 0ul; options = 0ul;
  meta_char_table = { esc = 0ul; anychar = 0ul; anytime = 0ul;
    zero_or_one_time = 0ul; one_or_more_time = 0ul; anychar_anytime = 0ul };
}"""

def lc(n):
    return n[0].lower() + n[1:]

for n in sorted(syms):
    k, c, builds = syms[n]
    if k != "D" or c != "public":
        continue
    if n.startswith("OnigEncoding"):
        o.write(f'[@@ rename_let "{n}"]\nlet {lc(n)} : onig_encoding_type = ' + ENC_LIT + '\n')
    elif n.startswith("OnigSyntax"):
        o.write(f'[@@ rename_let "{n}"]\nlet {lc(n)} : onig_syntax_type = ' + SYN_LIT + '\n')
    elif n == "OnigDefaultCaseFoldFlag":
        o.write(f'[@@ rename_let "{n}"]\nlet {lc(n)} : U32.t = 0x40000000ul\n')
    # OnigDefaultSyntax: in the C shell
o.write("\n")
for n in sorted(syms):
    k, c, builds = syms[n]
    if k != "F" or c != "public" or n in SKIP:
        continue
    if not posix and "default" not in builds:
        continue
    ret, params, h, line = protos[n]
    ps = split_params(params)
    args = "()" if ps == ["void"] else " ".join(f"(p{i}: {fty(t)})" for i, t in enumerate(ps))
    r = fty(ret)
    o.write(f"(* {h}:{line} *)\n")
    # a Pulse function (stateful): a pure unit-returning F* function would
    # be erased by extraction
    o.write(f"fn {n} {args}\n  requires emp\n")
    if r is not None:
        o.write(f"  returns _: {r}\n")
    o.write(f"  ensures emp\n{{\n  {ZERO[r] if r else '()'}\n}}\n")
o.close()
