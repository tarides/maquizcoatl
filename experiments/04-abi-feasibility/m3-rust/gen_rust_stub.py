#!/usr/bin/env python3
"""gen_rust_stub.py AUX AUXP SYMBOLS.tsv OUT.rs [posix]

Mechanism 3: generates one `#[unsafe(no_mangle)] pub extern "C" fn` per
public function exported by the oracle (symbols.tsv), from the
`gcc -aux-info` prototypes of the public headers. Each returns a fixed
value (zero / null). Parameter types are mapped to ABI-equivalent Rust
types: every pointer (data or function) to a raw pointer, C enums to
c_int, integer typedefs to their integer type. The variadic
onig_error_code_to_str is skipped (stable Rust cannot define it).
"""
import re, sys

aux, auxp, symf, out = sys.argv[1:5]
posix = len(sys.argv) > 5 and sys.argv[5] == "posix"
SKIP = {"onig_error_code_to_str"}
PROTO = re.compile(r"/\* (\S+?):(\d+):\w+ \*/ extern (.*?)\b(\w+) \((.*)\);$")

UINT = {"unsigned int", "OnigCodePoint", "OnigOptionType", "OnigCaseFoldType"}
INT = {"int", "OnigCalloutIn", "OnigCalloutType", "OnigRegSetLead", "OnigType"}
USIZE = {"size_t", "long unsigned int"}
PTR_TYPEDEFS = {"OnigEncoding", "OnigRegex", "OnigCalloutFunc", "OnigWarnFunc",
                "OnigCallbackEachMatchFunc"}

def rty(t):
    t = t.strip()
    if t == "void":
        return None
    if "*" in t or "(" in t or t in PTR_TYPEDEFS:
        return "*mut c_void"
    if t in UINT:
        return "c_uint"
    if t in INT:
        return "c_int"
    if t in USIZE:
        return "usize"
    raise SystemExit(f"unmapped C type: {t!r}")

def zero(r):
    return "core::ptr::null_mut()" if r == "*mut c_void" else "0"

def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

syms = {}
for l in open(symf).read().splitlines()[1:]:
    n, k, c, where, builds = l.split("\t")
    syms[n] = (k, c, builds)

protos = {}
for f in (aux, auxp):
    for l in open(f):
        m = PROTO.search(l.strip())
        if m and m.group(1).split("/")[-1].startswith("onig"):
            protos[m.group(4)] = (m.group(3), m.group(5), m.group(1).split("/")[-1], m.group(2))

with open(out, "w") as o:
    o.write("// Generated by gen_rust_stub.py: do not edit.\n")
    for n in sorted(syms):
        k, c, builds = syms[n]
        if k != "F" or c != "public" or n in SKIP:
            continue
        if not posix and "default" not in builds:
            continue
        ret, params, h, line = protos[n]
        ps = split_params(params)
        args = [] if ps == ["void"] else [f"_p{i}: {rty(t)}" for i, t in enumerate(ps)]
        r = rty(ret)
        o.write(f"// {h}:{line}\n#[unsafe(no_mangle)]\npub extern \"C\" fn {n}({', '.join(args)})")
        o.write(f" -> {r} {{ {zero(r)} }}\n" if r else " {}\n")
