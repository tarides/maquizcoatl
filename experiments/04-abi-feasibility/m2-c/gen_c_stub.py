#!/usr/bin/env python3
"""gen_c_stub.py AUX AUXP SYMBOLS.tsv OUTDIR

Mechanism 2 stub, generated mechanically from the public headers.
AUX and AUXP are `gcc -aux-info` outputs for a translation unit that
includes oniggnu.h (hence oniguruma.h) and one that includes
onigposix.h. For every public function exported by the oracle
(symbols.tsv), a definition returning a fixed value is emitted; every
public data symbol gets a file-scope initialised definition (encoding
structs hold function pointers). The variadic onig_error_code_to_str
is hand-written (va_list) and comes from stub_shell.c.

Writes OUTDIR/stub.c (default API) and OUTDIR/stub_posix.c (POSIX).
"""
import re, sys

aux, auxp, symf, outdir = sys.argv[1:5]
HANDWRITTEN = {"onig_error_code_to_str"}

syms = {}
for l in open(symf).read().splitlines()[1:]:
    n, k, c, where, builds = l.split("\t")
    syms[n] = (k, c, builds)

PROTO = re.compile(r"/\* (\S+?):(\d+):\w+ \*/ extern (.*?)\b(\w+) \((.*)\);$")

def protos(f):
    d = {}
    for l in open(f):
        m = PROTO.search(l.strip())
        if m and m.group(1).split("/")[-1].startswith("onig"):
            d[m.group(4)] = (m.group(3).strip(), m.group(5), m.group(1).split("/")[-1], m.group(2))
    return d

def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

def name_param(t, i):
    n = f"p{i}"
    if "(*" in t:                       # function pointer: T (*)(args)
        return t.replace("(*", f"(*{n}", 1)
    if t.endswith("]"):                 # array parameter
        j = t.index("[")
        return f"{t[:j]} {n}{t[j:]}"
    return f"{t} {n}"

def definition(name, ret, params):
    ps = split_params(params)
    if ps == ["void"]:
        plist, uses = "void", ""
    else:
        plist = ", ".join(name_param(t, i) for i, t in enumerate(ps))
        uses = " ".join(f"(void)p{i};" for i in range(len(ps)))
    body = uses
    if ret != "void":
        body += f" return ({ret})0;"
    return f"{ret} {name}({plist}) {{ {body} }}\n"

def emit(path, header_block, funcs, wanted, build):
    missing = []
    with open(path, "w") as o:
        o.write("/* Generated by gen_c_stub.py: do not edit. */\n")
        o.write(header_block)
        for n in sorted(wanted):
            k, c, builds = syms[n]
            if k != "F" or c != "public" or build not in builds or n in HANDWRITTEN:
                continue
            if n not in funcs:
                missing.append(n); continue
            ret, params, h, line = funcs[n]
            o.write(f"/* {h}:{line} */\n")
            o.write(definition(n, ret, params))
    return missing

main = protos(aux)
posix = protos(auxp)

# --- default API: functions from oniguruma.h / oniggnu.h, data symbols
head = '#include "oniggnu.h"\n#include "stub_data.h"\n\n'
m1 = emit(f"{outdir}/stub.c", head, main, list(syms), "default")

with open(f"{outdir}/stub.c", "a") as o:
    o.write("\n/* ---- data symbols ---- */\n")
    for n in sorted(syms):
        k, c, builds = syms[n]
        if k != "D" or c != "public":
            continue
        if n.startswith("OnigEncoding"):
            o.write(f'OnigEncodingType {n} = STUB_ENCODING("{n[12:]}");\n')
        elif n.startswith("OnigSyntax"):
            o.write(f"OnigSyntaxType {n} = STUB_SYNTAX;\n")
        elif n == "OnigDefaultSyntax":
            o.write("OnigSyntaxType* OnigDefaultSyntax = &OnigSyntaxOniguruma;\n")
        elif n == "OnigDefaultCaseFoldFlag":
            o.write("OnigCaseFoldType OnigDefaultCaseFoldFlag = ONIGENC_CASE_FOLD_MIN;\n")
        else:
            raise SystemExit(f"unhandled data symbol {n}")

# --- POSIX API (onigposix.h), compiled as upstream's regposix.c does
headp = ('#define regex_t onig_regex_t\n#include "oniguruma.h"\n#undef regex_t\n'
         '#include "onigposix.h"\n\n')
m2 = emit(f"{outdir}/stub_posix.c", headp, posix,
          [n for n in syms if n.startswith("onig_posix_")], "posix")

for n in m1 + m2:
    print(f"warning: no prototype for exported public symbol {n}", file=sys.stderr)
declared_only = sorted(n for n in list(main) + list(posix) if n not in syms)
print("declared in public headers but not exported by the oracle:",
      " ".join(declared_only) or "none")
